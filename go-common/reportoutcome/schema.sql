CREATE TABLE IF NOT EXISTS report_outcomes (
 report_seq INT NOT NULL PRIMARY KEY,
 consent_version INT NOT NULL DEFAULT 0,
 publication_mode VARCHAR(16) NOT NULL DEFAULT 'private',
 notices_mode VARCHAR(16) NOT NULL DEFAULT 'none',
 policy_version INT NOT NULL DEFAULT 1,
 processing_status VARCHAR(32) NOT NULL DEFAULT 'pending_analysis',
 decision_state VARCHAR(32) NOT NULL DEFAULT 'pending',
 reason_code VARCHAR(64) NOT NULL DEFAULT 'pending_analysis',
 outcome_json JSON NOT NULL,
 analysis_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 publication_status VARCHAR(16) NOT NULL DEFAULT 'private',
 publication_authorized BOOLEAN NOT NULL DEFAULT FALSE,
 public_event_status VARCHAR(16) NOT NULL DEFAULT 'none',
 public_event_attempts INT UNSIGNED NOT NULL DEFAULT 0,
 public_event_error_code VARCHAR(64) NULL,
 public_event_next_attempt_at DATETIME(6) NULL,
 match_reconciled BOOLEAN NOT NULL DEFAULT FALSE,
 reconcile_pending BOOLEAN NOT NULL DEFAULT TRUE,
 context_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 observation_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 observation_tokens JSON NULL,
 next_reconcile_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 KEY idx_report_outcome_recovery (reconcile_pending,next_reconcile_at,report_seq),
 KEY idx_report_outcome_context (context_key,publication_status,updated_at,report_seq),
 CONSTRAINT fk_report_outcome_report FOREIGN KEY (report_seq) REFERENCES reports(seq) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
